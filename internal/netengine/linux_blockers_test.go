type blockerFixture struct {
	e        *LinuxEngine
	r        *ScriptedRunner
	filter   string
	units    string
	commands []string
	loaded   map[string]string // command -> file content it loaded
}

func newBlockerFixture(t *testing.T) *blockerFixture {
	t.Helper()
	root := t.TempDir()
	write := func(p, s string) {
		full := filepath.Join(root, p)
		if err := os.MkdirAll(filepath.Dir(full), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(s), 0644); err != nil {
			t.Fatal(err)
		}
	}
	write("/proc/net/tcp", "  sl  local_address rem_address   st\n   0: 00000000:0016 00000000:0000 0A 00000000:00000000 00:00000000 00000000     0        0 1 1\n   1: 0100007F:0277 00000000:0000 0A 0\n")
	write("/proc/net/tcp6", "  sl  local_address\n   0: 00000000000000000000000000000000:0D3D 00000000000000000000000000000000:0000 0A 0\n")
	write("/proc/modules", "rfwlinux 16384 1 - Live 0x0\nnvidia 100 1 - Live 0x0\next4 1000 1 - Live 0x0\n")
	write("/sys/module/rfwlinux/taint", "OE\n")
	write("/sys/module/rfwlinux/srcversion", "ABC123\n")
	write("/sys/module/nvidia/taint", "POE\n")
	write("/sys/module/ext4/taint", "\n")
	write("/etc/modprobe.d/.keep", "")
	write("/lib/systemd/system/ufw.service", "[Service]\n")

	f := &blockerFixture{filter: iptFilterGood, loaded: map[string]string{},
		units: "ssh.service enabled enabled\nufw.service enabled enabled\nmyapp.service enabled enabled\n"}
	r := NewScriptedRunner()
	cfg := config.DefaultConfig()
	cfg.StateDir = filepath.Join(root, "state")
	f.e = &LinuxEngine{cfg: cfg, runner: r, fsRoot: root}
	f.r = r
	fail := func(ctx context.Context, args []string) (string, error) { return "", errors.New("not found") }
	r.On("iptables-legacy-save", fail)
	r.On("ip6tables-legacy-save", fail)
	r.On("ip6tables-nft-save", func(ctx context.Context, args []string) (string, error) { return "", nil })
	r.On("iptables-nft-save", func(ctx context.Context, args []string) (string, error) {
		if len(args) == 2 && args[1] == "nat" {
			return "*nat\n:PREROUTING ACCEPT [0:0]\nCOMMIT\n", nil
		}
		if len(args) == 2 {
			return SplitIptablesSave(f.filter)[0].Text, nil
		}
		return f.filter, nil
	})
	r.On("nft -s -t list ruleset", func(ctx context.Context, args []string) (string, error) { return nftRuleset, nil })
	r.On("nft -s list ruleset", func(ctx context.Context, args []string) (string, error) { return nftRuleset, nil })
	r.On("nft -s list table", func(ctx context.Context, args []string) (string, error) {
		for _, tb := range SplitNftTables(nftRuleset) {
			if tb.Name == strings.Join(args[3:], " ") {
				return tb.Text, nil
			}
		}
		return "", errors.New("No such file or directory")
	})
	record := func(name string) func(ctx context.Context, args []string) (string, error) {
		return func(ctx context.Context, args []string) (string, error) {
			f.commands = append(f.commands, name+" "+strings.Join(args, " "))
			if len(args) > 0 {
				if data, err := os.ReadFile(args[len(args)-1]); err == nil {
					f.loaded[name] = string(data)
				}
			}
			return "", nil
		}
	}
	r.On("nft -f", record("nft"))
	r.On("iptables-nft-restore", record("iptables-nft-restore"))
	r.On("systemctl disable", record("systemctl-disable"))
	r.On("systemctl enable", record("systemctl-enable"))
	r.On("modprobe -r", func(ctx context.Context, args []string) (string, error) {
		return "modprobe: FATAL: Module rfwlinux is in use.", errors.New("exit status 1")
	})
	r.On("modinfo", func(ctx context.Context, args []string) (string, error) { return "", nil })
	r.On("systemctl list-unit-files", func(ctx context.Context, args []string) (string, error) { return f.units, nil })
	r.On("systemctl list-units", func(ctx context.Context, args []string) (string, error) {
		return "ssh.service loaded active running OpenSSH\nufw.service loaded active exited UFW\nmyapp.service loaded active running App\n", nil
	})
	r.On("systemctl show", func(ctx context.Context, args []string) (string, error) {
		var b strings.Builder
		for _, u := range args[len(args)-strings.Count(f.units, ".service"):] {
			b.WriteString("Id=" + u + "\n")
			switch u {
			case "ufw.service":
				b.WriteString("FragmentPath=/lib/systemd/system/ufw.service\nExecStart={ path=/lib/ufw/ufw-init ; argv[]=/lib/ufw/ufw-init start quiet ; }\n\n")
			case "myapp.service":
				b.WriteString("FragmentPath=/etc/systemd/system/myapp.service\nExecStart={ path=/usr/bin/myapp ; argv[]=/usr/bin/myapp ; }\n\n")
			default:
				b.WriteString("FragmentPath=/lib/systemd/system/" + u + "\nExecStart={ path=/usr/sbin/sshd ; argv[]=/usr/sbin/sshd -D ; }\n\n")
			}
		}
		return b.String(), nil
	})
	return f
}

func compByName(cs []Component) map[string]Component {
	m := map[string]Component{}
	for _, c := range cs {
		m[c.Name] = c
	}
	return m
}

