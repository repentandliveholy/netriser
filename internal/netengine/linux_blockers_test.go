func TestLinuxComponents(t *testing.T) {
	f := newBlockerFixture(t)
	comps, err := f.e.Components(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	m := compByName(comps)
	for _, want := range []string{"iptables-nft:filter", "nft:inet filter", "nft:inet newblock", "unit:ufw.service", "unit:ssh.service", "kmod:rfwlinux", "kmod:nvidia"} {
		if _, ok := m[want]; !ok {
			t.Errorf("missing %s in %v", want, comps)
		}
	}
	for _, not := range []string{"nft:ip filter", "nft:ip nat", "iptables-nft:nat", "kmod:ext4"} {
		if _, ok := m[not]; ok {
			t.Errorf("%s listed (iptables-nft table, irrelevant or untainted)", not)
		}
	}
	if !m["unit:ufw.service"].Firewall || m["unit:myapp.service"].Firewall || m["unit:ssh.service"].Firewall {
		t.Errorf("firewall detection: %+v", m)
	}
	if !m["kmod:rfwlinux"].Untrusted {
		t.Errorf("unsigned out-of-tree module not untrusted")
	}
	if m["unit:ufw.service"].Changed.IsZero() {
		t.Errorf("unit file time not read")
	}
}

// A day after the working snapshot: ufw was enabled, a table dropping SSH
// appeared, the filter table gained a DROP rule and an unsigned module was
// loaded. Recovery stops ufw first, then removes the new table and puts the
// filter table back; the module waits for the untrusted rule.
func TestLinuxRecoveryFlow(t *testing.T) {
	f := newBlockerFixture(t)
	ctx := context.Background()
	t0 := time.Date(2026, 11, 20, 10, 0, 0, 0, time.UTC)
	f.units = "ssh.service enabled enabled\nmyapp.service enabled enabled\n"
	working, _ := f.e.Components(ctx)
	// The working host had no newblock table and no rfwlinux module yet.
	var known []Component
	for _, c := range working {
		if c.Name != "nft:inet newblock" && c.Name != "kmod:rfwlinux" {
			known = append(known, c)
		}
	}
	snap := &ComponentSnapshot{}
	MergeSnapshot(snap, known, t0)
	if err := f.e.SaveWorkingState(ctx, t0); err != nil {
		t.Fatal(err)
	}

	f.units = "ssh.service enabled enabled\nufw.service enabled enabled\nmyapp.service enabled enabled\n"
	f.filter = iptFilterBad
	now := t0.Add(24 * time.Hour)
	comps, _ := f.e.Components(ctx)
	p := BlockerPolicy{Snapshot: snap, KnownGoodBefore: now.Add(-time.Hour), Protected: DefaultProtectedUnixComponents}
	bs := SelectBlockers(comps, nil, p)
	if got := names(bs); got != "unit:ufw.service,iptables-nft:filter,nft:inet newblock,kmod:rfwlinux" {
		t.Fatalf("selected %q", got)
	}
	// Docker's new container alone would not have changed the filter table.
	dockerOnly := strings.Replace(iptFilterBad, "-A INPUT -p tcp --dport 22 -j DROP\n", "", 1)
	fpGood, _ := IptablesFingerprint(SplitIptablesSave(iptFilterGood)[0])
	fpDocker, _ := IptablesFingerprint(SplitIptablesSave(dockerOnly)[0])
	if fpGood != fpDocker {
		t.Fatal("container churn changed the fingerprint")
	}

	var results []ActionResult
	for _, b := range bs {
		results = append(results, f.e.DisableComponent(ctx, b))
	}
	if results[0].Status != ActionExecuted || f.commands[0] != "systemctl-disable disable --now ufw.service" {
		t.Fatalf("ufw: %+v %v", results[0], f.commands)
	}
	if results[1].Status != ActionExecuted || !strings.Contains(f.loaded["iptables-nft-restore"], "-A INPUT -i lo -j ACCEPT") || strings.Contains(f.loaded["iptables-nft-restore"], "--dport 22 -j DROP") {
		t.Fatalf("filter not put back: %+v\n%s", results[1], f.loaded["iptables-nft-restore"])
	}
	if results[2].Status != ActionExecuted || f.loaded["nft"] != "table inet newblock\ndelete table inet newblock\n" {
		t.Fatalf("new table not removed: %+v %q", results[2], f.loaded["nft"])
	}
	if results[3].Status != ActionPartial {
		t.Fatalf("module in use should be partial: %+v", results[3])
	}
	conf, err := os.ReadFile(filepath.Join(f.e.fsRoot, modprobeConf("rfwlinux")))
	if err != nil || !strings.Contains(string(conf), "blacklist rfwlinux") {
		t.Fatalf("module not blocked: %v %s", err, conf)
	}

	// Undo.
	for _, name := range []string{"iptables-nft:filter", "nft:inet newblock", "unit:ufw.service", "kmod:rfwlinux"} {
		if a := f.e.RestoreComponent(ctx, name, StartAuto); a.Status != ActionExecuted {
			t.Fatalf("restore %s: %+v", name, a)
		}
	}
	if !strings.Contains(f.loaded["iptables-nft-restore"], "--dport 22 -j DROP") || !strings.Contains(f.loaded["nft"], "tcp dport 22 drop") {
		t.Fatalf("saved copies not loaded back: %q %q", f.loaded["iptables-nft-restore"], f.loaded["nft"])
	}
	if _, err := os.Stat(filepath.Join(f.e.fsRoot, modprobeConf("rfwlinux"))); !os.IsNotExist(err) {
		t.Fatal("module still blocked after restore")
	}
}

