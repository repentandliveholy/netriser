func TestParsers(t *testing.T) {
	l := ParseDarwinNetstatListening("Active Internet connections (including servers)\nProto Recv-Q Send-Q  Local Address          Foreign Address        (state)\ntcp4       0      0  127.0.0.1.631          *.*                    LISTEN\ntcp46      0      0  *.22                   *.*                    LISTEN\ntcp6       0      0  fe80::1%lo0.5000       *.*                    LISTEN\ntcp4       0      0  192.168.1.5.52000      1.2.3.4.443            ESTABLISHED\n")
	if strings.Join(l[22], ",") != "0.0.0.0,::" || strings.Join(l[631], ",") != "127.0.0.1" || strings.Join(l[5000], ",") != "fe80::1" || len(l) != 3 {
		t.Fatalf("netstat: %v", l)
	}
	if on, ok := ParsePfStatus("No ALTQ support in kernel\nStatus: Enabled for 0 days 00:01:02\n"); !on || !ok {
		t.Fatal("pf status")
	}
	for text, want := range map[string]bool{
		"Firewall is enabled. (State = 1)":                                true,
		"Firewall is disabled. (State = 0)":                               false,
		"Firewall is set to block all non-essential incoming connections": true,
		"Block all DISABLED!":                                             false,
		"Block all ENABLED!":                                              true,
	} {
		if on, ok := ParseOnOff(text); !ok || on != want {
			t.Errorf("ParseOnOff(%q) = %v %v", text, on, ok)
		}
	}
	ext := ParseNetworkExtensions("2 extension(s)\n--- com.apple.system_extension.network_extension\nenabled\tactive\tteamID\tbundleID (version)\tname\t[state]\n*\t*\tVBG97UB4TA\tcom.objective-see.lulu.extension (2.4.1/2.4.1)\tLuLu\t[activated enabled]\n--- com.apple.system_extension.endpoint_security\n*\t*\tX\tcom.example.es (1.0/1)\tES\t[activated enabled]\n")
	if len(ext) != 1 || ext["com.objective-see.lulu.extension"] != "2.4.1/2.4.1" {
		t.Fatalf("extensions: %v", ext)
	}
	dis := ParseLaunchctlDisabled("disabled services = {\n\t\"com.foo.fw\" => disabled\n\t\"com.bar\" => enabled\n\t\"com.old\" => true\n}\n")
	if !dis["com.foo.fw"] || dis["com.bar"] || !dis["com.old"] {
		t.Fatalf("disabled: %v", dis)
	}
	if !IsFirewallUnit("myfw.service", "{ path=/usr/sbin/nft ; argv[]=/usr/sbin/nft -f /etc/my.nft ; }") || IsFirewallUnit("myapp.service", "/usr/bin/myapp --tc=1") {
		t.Fatal("firewall unit detection")
	}
	if ModuleUntrusted("POE", "") != true || ModuleUntrusted("O", "Build key") || ModuleUntrusted("P", "") {
		t.Fatal("module trust")
	}
}

func TestRulesStoreVersions(t *testing.T) {
	s := rulesStore{dir: t.TempDir()}
	t0 := time.Unix(1_700_000_000, 0)
	for i, fp := range []string{"sha256:aa", "sha256:aa", "sha256:bb", "sha256:cc"} {
		if err := s.save("nft:inet filter", fp, fp, t0.Add(time.Duration(i)*time.Hour)); err != nil {
			t.Fatal(err)
		}
	}
	if n := len(s.versions("nft:inet filter")); n != 3 {
		t.Fatalf("%d versions, want 3 (same fingerprint saved once)", n)
	}
	// Current is cc (bad, saved at +3h); block at +3h30: known good before
	// +2h30 -> bb.
	if got, ok := s.working("nft:inet filter", "sha256:cc", t0.Add(150*time.Minute)); !ok || got != "sha256:bb" {
		t.Fatalf("working copy %q %v", got, ok)
	}
	if _, ok := s.working("nft:inet filter", "sha256:cc", t0.Add(-time.Hour)); ok {
		t.Fatal("copy newer than the limit returned")
	}
}

// Right after installation the snapshot is minutes old: unchanged tables are
// still trusted (the snapshot was taken while the self-probe passed), a new
// table is not.
func TestFreshSnapshotTrustsUnchangedRules(t *testing.T) {
	now := time.Date(2026, 11, 24, 12, 0, 0, 0, time.UTC)
	old := Component{Name: "nft:inet filter", Kind: KindRules, Running: true, Start: StartAuto, Image: "sha256:aa"}
	snap := &ComponentSnapshot{}
	MergeSnapshot(snap, []Component{old}, now.Add(-10*time.Minute))
	added := Component{Name: "nft:inet block", Kind: KindRules, Running: true, Start: StartAuto, Image: "sha256:bb"}
	bs := SelectUnixBlockers([]Component{old, added}, BlockerPolicy{Snapshot: snap, KnownGoodBefore: now.Add(-time.Hour)})
	if got := names(bs); got != "nft:inet block" || !bs[0].New {
		t.Fatalf("selected %q", got)
	}
}
