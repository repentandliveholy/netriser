package netengine

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strings"
	"time"
)

type dnsBaseline struct {
	Path            string      `json:"path"`
	Target          string      `json:"target"`
	Content         []byte      `json:"content"`
	Mode            os.FileMode `json:"mode"`
	ManagedResolved bool        `json:"managed_resolved"`
}

func (e *LinuxEngine) resolverPath() string {
	if e.resolvConfPath != "" {
		return e.resolvConfPath
	}
	return "/etc/resolv.conf"
}

func resolvedManagedPath(path string) bool {
	return path == "/run/systemd/resolve/stub-resolv.conf" || path == "/run/systemd/resolve/resolv.conf"
}

func hasNameserver(data []byte) bool {
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(strings.SplitN(line, "#", 2)[0])
		if len(fields) >= 2 && fields[0] == "nameserver" && net.ParseIP(strings.SplitN(fields[1], "%", 2)[0]) != nil {
			return true
		}
	}
	return false
}

func atomicDNSFile(path string, data []byte, mode os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".dns-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	defer tmp.Close()
	if err = tmp.Chmod(mode.Perm()); err != nil {
		return err
	}
	if _, err = tmp.Write(data); err != nil {
		return err
	}
	if err = tmp.Sync(); err != nil {
		return err
	}
	if err = tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// Called only after successful system DNS lookups. A recent file change is not
// cached: Go's system resolver may still be using its previous 5-second config.
func (e *LinuxEngine) CaptureDNSBaseline(ctx context.Context) error {
	path := e.resolverPath()
	target, err := filepath.EvalSymlinks(path)
	if err != nil {
		return err
	}
	info, err := os.Stat(target)
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() || info.Size() > 65536 {
		return fmt.Errorf("invalid resolver file")
	}
	if time.Since(info.ModTime()) < 5*time.Second {
		return nil
	}
	data, err := os.ReadFile(target)
	if err != nil {
		return err
	}
	if !hasNameserver(data) {
		return fmt.Errorf("resolver has no valid nameserver; not caching")
	}
	b := dnsBaseline{Path: path, Target: target, Content: data, Mode: info.Mode().Perm()}
	if resolvedManagedPath(target) {
		if _, err := e.run(ctx, 2*time.Second, "systemctl", "is-active", "--quiet", "systemd-resolved"); err != nil {
			return fmt.Errorf("managed DNS service is not active")
		}
		b.ManagedResolved = true
	}
	encoded, err := json.MarshalIndent(b, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(e.cfg.StateDir, 0750); err != nil {
		return err
	}
	return atomicDNSFile(filepath.Join(e.cfg.StateDir, "dns-baseline.json"), encoded, 0600)
}

// Restore the last healthy file; restart only the resolver that owned it.
// Never changes routes, overlay services, per-link DNS policy or reboot state.
func (e *LinuxEngine) RestoreDNS(ctx context.Context) ([]ActionResult, error) {
	act := ActionResult{Type: ActionRestoreDNS, Target: e.resolverPath(), Status: ActionFailed}
	fail := func(err error) ([]ActionResult, error) { act.Error = err.Error(); return []ActionResult{act}, err }
	data, err := os.ReadFile(filepath.Join(e.cfg.StateDir, "dns-baseline.json"))
	if err != nil {
		// A first-start failure has no trusted backup. A known managed stub can
		// still be regenerated by its owner, without inventing a DNS server.
		target, pathErr := filepath.EvalSymlinks(e.resolverPath())
		if os.IsNotExist(err) && pathErr == nil && resolvedManagedPath(target) {
			_, err = e.run(ctx, 10*time.Second, "systemctl", "restart", "systemd-resolved")
			if err != nil {
				return fail(err)
			}
			act.Status, act.Description = ActionExecuted, "Regenerated managed resolver using systemd-resolved"
			return []ActionResult{act}, nil
		}
		return fail(fmt.Errorf("no trusted DNS baseline: %w", err))
	}
	var b dnsBaseline
	if err := json.Unmarshal(data, &b); err != nil {
		return fail(err)
	}
	if b.Path != e.resolverPath() || !hasNameserver(b.Content) || len(b.Content) > 65536 {
		return fail(fmt.Errorf("invalid DNS baseline; refusing resolver changes"))
	}
	if b.ManagedResolved {
		if !resolvedManagedPath(b.Target) {
			return fail(fmt.Errorf("unrecognized managed resolver path"))
		}
		if _, err := e.run(ctx, 10*time.Second, "systemctl", "restart", "systemd-resolved"); err != nil {
			return fail(err)
		}
	}
	target, err := filepath.EvalSymlinks(b.Path)
	if err != nil {
		return fail(err)
	}
	if target != b.Target {
		return fail(fmt.Errorf("resolver target changed; refusing to overwrite %s", target))
	}
	current, err := os.ReadFile(target)
	if err != nil {
		return fail(err)
	}
	if !bytes.Equal(current, b.Content) {
		// Keep the failing content for diagnosis before replacing the target.
		if err := atomicDNSFile(filepath.Join(e.cfg.StateDir, "dns-resolv.failed"), current, 0600); err != nil {
			return fail(err)
		}
		if err := atomicDNSFile(target, b.Content, b.Mode); err != nil {
			return fail(err)
		}
	}
	act.Status, act.Description = ActionExecuted, "Restored last healthy resolver configuration without reboot"
	return []ActionResult{act}, nil
}
